async function svPickMusic() {
  SV.musicErr = "";
  let bytes = null, name = "";
  const r = await svApi("/api/studio/music/pick", {});
  if (r.ok && r.url) { // (the address serves the file once: it is read whole and kept here)
    SV.musicBusy = "正在读取音乐…"; svRender();
    try {
      const resp = await fetch(r.url);
      if (!resp.ok) throw new Error("HTTP " + resp.status);
      bytes = new Uint8Array(await resp.arrayBuffer()); name = r.name || "音乐";
    } catch (e) { SV.musicBusy = ""; SV.musicErr = "无法读取音乐：" + e.message; svRender(); return; }
  } else if (r.cancelled) return;
  else if (/ 404/.test(r.err || "")) { // (a program without the route: the browser's own file picker)
    const f = await svFileInput("audio/*,.mp3,.wav,.ogg,.oga,.m4a,.aac,.flac,.opus");
    if (!f) return;
    if (f.size > 200 * 1024 * 1024) { SV.musicErr = "音乐文件太大（超过 200 MB）"; svRender(); return; }
    bytes = new Uint8Array(await f.arrayBuffer()); name = f.name;
  } else { SV.musicErr = r.err || "无法打开文件选择窗口"; svRender(); return; }
  await svLoadMusic(bytes, name);
}
