// the vision check: the middle of each scene drawn small, sent to the AI with the edit
async function svLook() {
  const E = SV.E, SC = svSC();
  SV.look = { busy: true }; svRender();
  let mids = SC.midpoints(E);
  if (mids.length > 8) mids = Array.from({ length: 8 }, (_, k) => mids[Math.round(k * (mids.length - 1) / 7)]);
  // JPEG, 768 px on the long side, quality 0.8; the whole request under the program's 4 MB (a frame that would pass it
  // goes again at a lower quality, else is left out)
  const frames = [], long = 768, k = Math.min(1, long / Math.max(E.w, E.h)), w = Math.round(E.w * k / 2) * 2, h = Math.round(E.h * k / 2) * 2, room = 3.7e6;
  let size = 0;
  try {
    await svNeed("studio-export.js", "StudioExport");
    for (const m of mids) {
      const c = svCanvas(w, h), R = SC.renderer(E, SV.res, { w, h, qr: svQR, canvas: svCanvas });
      SC.draw(c.getContext("2d"), m.t, R);
      for (const q of [0.8, 0.6, 0.45]) {
        const blob = c.convertToBlob ? await c.convertToBlob({ type: "image/jpeg", quality: q }) : await new Promise(ok => c.toBlob(ok, "image/jpeg", q));
        const data = "data:image/jpeg;base64," + await StudioExport.b64(new Uint8Array(await blob.arrayBuffer()));
        if (size + data.length + 200 > room) continue;
        frames.push({ scene: m.id, at: m.t, data }); size += data.length + 200; break;
      }
    }
    if (!frames.length) throw new Error("画面太大");
  } catch (e) { SV.look = { err: "无法生成画面：" + (e && e.message || e) }; if (svOpenNow() && SV.step === 5) svRender(); return; }
  const r = await svApi("/api/studio/look", { job: SV.job, frames });
  SV.look = r.ok ? { text: r.summary || "", notes: (r.issues || []).map(x => ({ scene: x.scene, at: x.at, note: x.text })), model: r.model || "" } : { err: r.err || "检查失败" };
  if (svOpenNow() && SV.step === 5) svRender();
}
