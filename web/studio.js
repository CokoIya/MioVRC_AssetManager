// A file to the program: begin (where, under which name), its bytes in parts of up to `chunk` (8 MB) as the body of
// /api/studio/save/chunk?id=…&off=…, end (the program checks the file is what its name says and moves it into place).
function svCancelled(signal) {
  if (signal && signal.cancelled) throw Object.assign(new Error("已取消"), { cancelled: true });
}
async function svSave(kind, ext, bytes, onPart, tag, signal) {
  svCancelled(signal);
  const b = await svApi("/api/studio/save/begin", { kind, name: svFileName(ext, tag), size: bytes.length, folder: SV.dir || "" });
  if (!b.ok) throw new Error(b.err || "无法保存");
  const step = Math.max(1 << 20, Math.min(b.chunk || SV_CHUNK, SV_CHUNK));
  try {
    for (let off = 0; off < bytes.length;) {
      const end = Math.min(bytes.length, off + step);
      let failures = 0;
      while (off < end) {
        svCancelled(signal);
        let r;
        try {
          const resp = await fetch(`/api/studio/save/chunk?id=${encodeURIComponent(b.id)}&off=${off}`, { method: "POST",
            headers: { "X-Token": window.API_TOKEN, "Content-Type": "application/octet-stream" }, body: bytes.subarray(off, end) });
          r = resp.ok ? await resp.json() : { ok: false, err: `程序返回错误 ${resp.status}（/api/studio/save/chunk）` };
        } catch (e) { r = { ok: false, err: "无法连接到程序" }; }
        svCancelled(signal);
        const got = r.got;
        if (!Number.isInteger(got) || got < off || got > end || got === off) {
          if (++failures > 2) throw new Error(r.err || "保存中断");
          continue;
        }
        // A lost response can leave this part on disk; the next answer gives its actual offset.
        off = got;
        if (!r.ok && off < end && ++failures > 2) throw new Error(r.err || "保存中断");
        if (onPart) onPart(off / bytes.length);
      }
    }
    svCancelled(signal);
    const e = await svApi("/api/studio/save/end", { id: b.id });
    if (!e.ok) throw new Error(e.err || "保存失败");
    return e.path || b.path || "";
  } catch (err) {
    await svApi("/api/studio/save/end", { id: b.id, cancel: true });
    throw err;
  }
}
