// ---------- the sources: pictures the backend names, loaded once ----------
function svSources(src) {
  SV.sources = src || {};
  for (const [key, s] of Object.entries(SV.sources)) {
    const sig = JSON.stringify([s.url, s.urls, s.frames, s.cols]);
    const have = SV.res[key];
    if (have && have.sig === sig) { Object.assign(have, { box: s.box, face: s.face, label: s.label, alpha: s.alpha }); continue; }
    // (a picture taken again: the old one stays on screen until the new one is there)
    const r = { sig, w: s.w, h: s.h, box: s.box, face: s.face, label: s.label, alpha: s.alpha, state: "loading" };
    if (have && have.state === "ok") have.next = sig; else SV.res[key] = r;
    svLoadSource(r, s).then(() => { r.state = "ok"; if (SV.res[key] === have && have.next === sig || SV.res[key] === r) SV.res[key] = r; SV.resVer++; svRedrawSoon(); },
      () => { r.state = "error"; if (SV.res[key] === r) svRedrawSoon(); else if (have) have.next = ""; });
  }
  for (const k of Object.keys(SV.res)) if (!SV.sources[k]) delete SV.res[k];
}
const svImgQueue = { n: 0, wait: [] };
function svImg(url) {
  return new Promise((ok, bad) => {
    const go = () => {
      svImgQueue.n++;
      const im = new Image(), done = () => { svImgQueue.n--; const f = svImgQueue.wait.shift(); if (f) f(); };
      im.decoding = "async";
      im.onload = () => { (im.decode ? im.decode() : Promise.resolve()).catch(() => {}).then(() => { done(); ok(im); }); };
      im.onerror = () => { done(); bad(new Error(url)); };
      im.src = url;
    };
    if (svImgQueue.n < 6) go(); else svImgQueue.wait.push(go);
  });
}
// a spin is a list of frame addresses (urls), or one picture holding its frames side by side (cols to a row)
async function svLoadSource(r, s) {
  if (Array.isArray(s.urls) && s.urls.length) { r.frames = await Promise.all(s.urls.map(svImg)); r.w = r.w || r.frames[0].naturalWidth; r.h = r.h || r.frames[0].naturalHeight; return; }
  const im = await svImg(s.url);
  if (s.frames > 1 && window.createImageBitmap) {
    const cols = s.cols || s.frames, rows = Math.ceil(s.frames / cols), fw = s.w || Math.floor(im.naturalWidth / cols), fh = s.h || Math.floor(im.naturalHeight / rows);
    r.frames = await Promise.all(Array.from({ length: s.frames }, (_, i) => createImageBitmap(im, (i % cols) * fw, Math.floor(i / cols) * fh, fw, fh)));
    r.w = fw; r.h = fh; return;
  }
  r.img = im; r.w = r.w || im.naturalWidth; r.h = r.h || im.naturalHeight;
}
