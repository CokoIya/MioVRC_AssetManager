function svBoardAction(a, el) {
  const id = SV.sel;
  const at = (e, fn) => { const s = svScene(e, id); if (s) fn(s, e.scenes.indexOf(s), e); };
  switch (a) {
    // (the scenes always fill the video: a beat one scene gains, a neighbour gives; a new scene takes half of the
    // selected one; a removed scene's beats go to the one before)
    case "len+": if (svSpare(SV.edit, id)) svChange(e => at(e, (s, i) => { const d = svSpare(e, id); d.len_beats--; s.len_beats++; })); break;
    case "len-": svChange(e => at(e, (s, i) => { if (s.len_beats < 2) return; s.len_beats--; (e.scenes[i + 1] || e.scenes[i - 1] || s).len_beats++; })); break;
    case "sc-left": case "sc-right": svChange(e => at(e, (s, i) => { const j = i + (a === "sc-right" ? 1 : -1); if (j < 0 || j >= e.scenes.length) return; e.scenes[i] = e.scenes[j]; e.scenes[j] = s; })); break;
    case "sc-dup": case "sc-add": {
      const s0 = svScene(null, id);
      if (!s0 || (s0.len_beats || 0) < 2 && !svSpare(SV.edit, id)) { toast("这一镜只有一拍，先加长再插入"); break; }
      svChange(e => at(e, (s, i) => {
        let n = Math.floor(s.len_beats / 2);
        if (n < 1) { svSpare(e, id).len_beats--; s.len_beats++; n = 1; }
        s.len_beats -= n;
        const shot = Object.keys(SV.sources).find(k => svSC().kindOf(k) === "shot") || Object.keys(SV.sources)[0];
        const c = a === "sc-dup" ? JSON.parse(JSON.stringify(s)) : { layout: "full", transition: svSC().STYLES[SV.E.style].trans[0] || "cut", layers: shot ? [{ src: shot, slot: 0 }] : [] };
        c.id = svNewId(e); c.len_beats = n;
        e.scenes.splice(i + 1, 0, c); SV.sel = c.id;
      }));
      break;
    }
    case "sc-del": svChange(e => at(e, (s, i) => { if (e.scenes.length < 2) return; (e.scenes[i - 1] || e.scenes[i + 1]).len_beats += s.len_beats; e.scenes.splice(i, 1); SV.sel = (e.scenes[i] || e.scenes[i - 1]).id; })); break;
    case "ly-pic": case "ly-text": case "ly-shape": svChange(e => at(e, s => {
      s.layers = s.layers || [];
      if (s.layers.length >= 12) return;
      const pic = Object.keys(SV.sources).find(k => svSC().kindOf(k) === "shot") || Object.keys(SV.sources)[0];
      if (a === "ly-pic" && pic) s.layers.push({ src: pic, slot: 0, fit: SV.sources[pic] && SV.sources[pic].alpha ? "contain" : "cover" });
      if (a === "ly-text") s.layers.push({ src: "text", text: "", box: [0.08, 0.72, 0.84, 0.14], size: 0.07, anim: { in: "fade" }, z: 5 });
      if (a === "ly-shape") s.layers.push({ src: "shape:sparkle", box: [0.82, 0.08, 0.1, 0.1], anim: { in: "pop" }, z: 6 });
    })); break;
    case "ly-up": case "ly-down": case "ly-del": {
      const k = +el.closest("[data-svly]").dataset.svly;
      svChange(e => at(e, s => {
        const L = s.layers;
        if (a === "ly-del") { L.splice(k, 1); return; }
        const j = k + (a === "ly-up" ? 1 : -1); if (j < 0 || j >= L.length) return;
        // (drawn in order of z, then of the list: the two swap places and z values)
        const t = L[k]; L[k] = L[j]; L[j] = t;
        const zk = L[k].z || 0, zj = L[j].z || 0; L[k].z = zj; L[j].z = zk;
      }));
      break;
    }
    case "cap-add": svChange(e => at(e, s => {
      e.captions = e.captions || [];
      if (e.captions.length >= 40) return;
      e.captions.push({ text: "", pos: "auto", at_beat: s.at_beat, len_beats: Math.min(4, s.len_beats) });
    })); break;
    case "cap-del": case "cap-at-": case "cap-at+": case "cap-len-": case "cap-len+": {
      const k = +el.closest("[data-svcap]").dataset.svcap;
      svChange(e => {
        const c = e.captions[k]; if (!c) return;
        if (a === "cap-del") e.captions.splice(k, 1);
        else if (a === "cap-at-" || a === "cap-at+") c.at_beat = Math.max(0, c.at_beat + (a === "cap-at+" ? 1 : -1));
        else c.len_beats = Math.max(1, c.len_beats + (a === "cap-len+" ? 1 : -1));
      });
      break;
    }
  }
}
// a field of the scene, a layer or a caption changed
function svFieldChange(t) {
  const id = SV.sel;
  if (t.dataset.svf) { const v = t.value, f = t.dataset.svf; svChange(e => { const s = svScene(e, id); if (s) s[f] = v; }); return true; }
  if (t.dataset.svlf) {
    const k = +t.closest("[data-svly]").dataset.svly, f = t.dataset.svlf;
    svChange(e => {
      const s = svScene(e, id), l = s && s.layers[k]; if (!l) return;
      l.anim = l.anim || {};
      switch (f) {
        case "src": l.src = t.value; break;
        case "shape": l.src = "shape:" + t.value; break;
        case "slot": if (t.value !== "box") { l.slot = +t.value; delete l.box; } break;
        case "fit": l.fit = t.value; break;
        case "kb": if (t.checked) l.anim.kb = { from: [0.5, 0.45, 1], to: [0.5, 0.4, 1.12] }; else delete l.anim.kb; break;
        case "text": l.text = t.value.slice(0, 80); break;
        case "font": if (t.value) l.font = t.value; else delete l.font; break;
        case "size": l.size = Math.max(0.02, Math.min(0.2, (+t.value || 6) / 100)); break;
        case "in": case "out": l.anim[f] = t.value; break;
      }
    });
    return true;
  }
  if (t.dataset.svcf) {
    const k = +t.closest("[data-svcap]").dataset.svcap, f = t.dataset.svcf;
    svChange(e => { const c = e.captions[k]; if (c) c[f] = f === "text" ? t.value.slice(0, 60) : t.value; });
    return true;
  }
  return false;
}
// a shot taken again as it was asked for (the job's specs), with the framing or the angle changed when chosen
async function svReshoot(ids, opt, retrySpecs) {
  if (svBusy()) return;
  const specs = retrySpecs || (SV.status && SV.status.specs) || {}, framing = opt ? opt.framing : "", yaw = opt ? opt.yaw : "";
  const shots = ids.map(id => Object.assign({}, specs[id] || { id, alpha: true }, framing ? { framing } : {}, yaw !== "" && yaw !== undefined ? { yaw: +yaw } : {}));
  if (!shots.length) return;
  const project = SV.project, job = SV.job;
  SV.starting = true; SV.lastAction = "shoot"; SV.lastShots = shots;
  clearTimeout(SV.polling); SV.pollSeq++;
  const r = await svApi("/api/studio/shoot", { project, job, shots });
  if (project !== SV.project || job !== SV.job) return;
  SV.starting = false;
  if (!r.ok) { toast(r.err || "无法开始拍摄", 4000); return; }
  SV.directing = false;
  SV.status = Object.assign({}, SV.status, { busy: "shoot", err: "", progress: { what: "shoot", done: 0, total: shots.length } });
  svRender();
  svPoll();
}
function svRetry() {
  if (SV.lastAction !== "shoot") return svDirect();
  const st = SV.status || {}, failed = Object.keys(st.shots || {}).filter(id => st.shots[id] && st.shots[id].err);
  const specs = Object.assign({}, st.specs, Object.fromEntries(SV.lastShots.map(s => [s.id, s])));
  return svReshoot(failed.length ? failed : SV.lastShots.map(s => s.id), null, specs);
}

